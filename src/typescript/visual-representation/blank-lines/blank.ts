class Calculator {



    add(a: number, b: number): number {



        return a + b;



    }
    subtract(a: number, b: number): number {
        return a - b;
    }
    multiply(a: number, b: number, c: number, d: number,
             e: number): number {
        return a * b * c * d * e;
    }
}
